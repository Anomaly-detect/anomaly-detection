"""
Predicted Frame Rendering Engine
---------------------------------
Location: d:/anomaly-detection/src/predicted_frame.py

Provides modular utilities for rendering and exporting predicted video frames
generated directly by the ASTNet prediction head (self.final) into HTML5-compatible
H.264 MP4 videos.
"""

import os
import tempfile
import subprocess
import cv2
import numpy as np


def render_predicted_frame_video(
    video_path: str,
    fps: float,
    frame_predicted_frames: dict,
    output_path: str = None,
) -> str:
    """
    Render predicted next frames generated by ASTNet self.final into an H.264 MP4 video.

    Args:
        video_path: Path to the original input video.
        fps: Playback frame rate.
        frame_predicted_frames: Dict mapping frame_index -> predicted RGB frame [H, W, 3] in [0, 255].
        output_path: Optional destination video file path. Defaults to temp directory.

    Returns:
        Absolute path to the rendered, web-compatible MP4 video.
    """
    cap = cv2.VideoCapture(video_path)
    orig_w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    orig_h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    if orig_w <= 0 or orig_h <= 0:
        cap.release()
        return video_path

    if output_path is None:
        temp_dir = tempfile.gettempdir()
        base_name = os.path.splitext(os.path.basename(video_path))[0]
        output_path = os.path.join(temp_dir, f"{base_name}_predicted.mp4")

    fourcc = cv2.VideoWriter_fourcc(*"mp4v")
    writer = cv2.VideoWriter(output_path, fourcc, fps, (orig_w, orig_h))

    first_available_pred = None
    if frame_predicted_frames:
        min_key = min(frame_predicted_frames.keys())
        first_available_pred = frame_predicted_frames[min_key]

    f_idx = 0
    while cap.isOpened():
        ret, frame = cap.read()
        if not ret:
            break

        if f_idx in frame_predicted_frames:
            pred_rgb = frame_predicted_frames[f_idx]
            pred_bgr = cv2.cvtColor(pred_rgb, cv2.COLOR_RGB2BGR)
        elif first_available_pred is not None:
            pred_bgr = cv2.cvtColor(first_available_pred, cv2.COLOR_RGB2BGR)
        else:
            pred_bgr = frame

        # Resize to original resolution if needed
        if (pred_bgr.shape[1], pred_bgr.shape[0]) != (orig_w, orig_h):
            pred_bgr = cv2.resize(pred_bgr, (orig_w, orig_h), interpolation=cv2.INTER_LINEAR)

        writer.write(pred_bgr)
        f_idx += 1

    cap.release()
    writer.release()

    # Re-encode to H.264 (yuv420p) for standard HTML5 browser video playback
    try:
        import imageio_ffmpeg
        ffmpeg_exe = imageio_ffmpeg.get_ffmpeg_exe()
        temp_h264 = output_path + ".h264.mp4"
        cmd = [
            ffmpeg_exe, "-y",
            "-i", output_path,
            "-c:v", "libx264",
            "-pix_fmt", "yuv420p",
            "-movflags", "+faststart",
            "-preset", "veryfast",
            temp_h264,
        ]
        res = subprocess.run(cmd, capture_output=True)
        if res.returncode == 0 and os.path.exists(temp_h264):
            os.replace(temp_h264, output_path)
    except Exception:
        pass

    return output_path


class PredictedFrameRenderer:
    """
    Class-based interface for predicted frame export and visualization.
    """

    def __init__(self, fps: float = 30.0):
        self.fps = fps

    def render_video(
        self,
        video_path: str,
        frame_predicted_frames: dict,
        output_path: str = None,
    ) -> str:
        return render_predicted_frame_video(
            video_path=video_path,
            fps=self.fps,
            frame_predicted_frames=frame_predicted_frames,
            output_path=output_path,
        )
